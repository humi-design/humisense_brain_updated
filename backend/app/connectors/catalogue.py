"""Connector catalogue.

Every integration target from the Layer 1 brief is catalogued here with an
honest :class:`ImplementationState`.  Only connectors that have a working
implementation and a registered factory are ``is_installable``.

State meanings
--------------
PLANNED             - target known, no code yet.
SCAFFOLDED          - definition + interface exist, no working calls.
IMPLEMENTED         - code path exists and unit-tested against fixtures.
TESTED              - automated tests cover the connector contract.
INTEGRATION_VERIFIED- exercised against a real provider environment.
PRODUCTION_READY    - verified + hardened + documented for production use.

Nothing in this file claims a live provider integration.  Verified state is
only ever set after a real connection has been made (see docs/AUDIT.md).
"""

from __future__ import annotations

from app.schemas.contracts import (
    AuthType,
    Capability,
    ConnectorCapability,
    ConnectorCategory,
    ConnectorDefinition,
    ImplementationState,
)

_F = ImplementationState.PLANNED


def _def(
    connector_id: str,
    provider: str,
    display_name: str,
    category: ConnectorCategory,
    description: str,
    auth_types: list[AuthType],
    *,
    state: ImplementationState = _F,
    capabilities: list[Capability] | None = None,
    required_scopes: list[str] | None = None,
    supported_resources: list[str] | None = None,
    supports_webhooks: bool = False,
    supports_incremental: bool = False,
    is_read_only: bool = True,
    requires_on_premise: bool = False,
    required_license: str | None = None,
    known_limitations: list[str] | None = None,
    documentation_url: str | None = None,
) -> ConnectorDefinition:
    caps = capabilities or [Capability.READ]
    return ConnectorDefinition(
        connector_id=connector_id,
        provider=provider,
        display_name=display_name,
        category=category,
        description=description,
        auth_types=auth_types,
        capabilities=[
            ConnectorCapability(capability=c, implementation_state=state) for c in caps
        ],
        required_scopes=required_scopes or [],
        supported_resources=supported_resources or [],
        supports_webhooks=supports_webhooks,
        supports_incremental=supports_incremental,
        is_read_only=is_read_only,
        requires_on_premise=requires_on_premise,
        required_license=required_license,
        known_limitations=known_limitations or [],
        implementation_state=state,
        documentation_url=documentation_url,
    )


